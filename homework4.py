number = int(input("Введіть число: "))

# Маска для 3-го біта (рахунок починається з 0)
mask = 1 << 3

# Перевірка, чи увімкнений 3-й біт
bit_enabled = (number & mask) != 0

# Множення числа на 8 за допомогою зсуву вліво
result = number << 3

print(f"3-й біт увімкнений: {bit_enabled}")
print(f"Число * 8: {result}")